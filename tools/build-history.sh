#!/usr/bin/env bash
# Rebuilds main as one commit per supported Spark release, oldest first, each tagged.
#
# The history here is a version ladder, not a timeline: commit N is "the connector, built
# for Spark N", not "what changed on some date". Read it by checking out a tag, not by
# reading the log top to bottom.
#
#   tools/build-history.sh
#
# Destructive: it replaces main. The previous main is left behind as a branch named
# pre-history-<short-sha> so nothing is lost if this turns out wrong.
set -euo pipefail
cd "$(dirname "$0")/.."

[ -z "$(git status --porcelain)" ] || { echo "working tree is dirty; commit or stash first"; exit 1; }

PREV=$(git rev-parse --short HEAD)
git branch "pre-history-$PREV" 2>/dev/null || true
echo "previous main kept as pre-history-$PREV"

VERSIONS=$(python3 -c "import json;print(' '.join(json.load(open('tools/versions.json'))))")

git checkout -q --orphan version-ladder
git rm -rq --cached . > /dev/null

first=1
for v in $VERSIONS; do
  python3 tools/retarget.py "$v" > /dev/null
  variant=$(python3 -c "import json;print(json.load(open('tools/versions.json'))['$v']['variant'])")
  binaries=$(python3 -c "import json;print(', '.join(sorted(json.load(open('tools/versions.json'))['$v']['scala'])))")
  kafka=$(python3 -c "import json;print(json.load(open('tools/versions.json'))['$v']['kafka'])")
  java=$(python3 -c "import json;print(json.load(open('tools/versions.json'))['$v']['java'])")

  git add -A
  if [ "$first" = 1 ]; then
    subject="Komiter $v — Kafka offset committer for Spark Structured Streaming"
    first=0
  else
    subject="Komiter $v"
  fi
  git commit -q -m "$subject" -m \
"Targets Spark $v: source variant $variant, Scala $binaries, Kafka clients $kafka,
Java $java. Every one of those is taken from Apache Spark's own pom for this release
rather than chosen here, so the connector cannot pull a Kafka client or a Scala runtime
that differs from the one this Spark was built against.

Generated by tools/retarget.py; see tools/README.md."
  git tag -f "v$v" -m "Komiter $v (Spark $v)" > /dev/null
  printf '  %-7s %s\n' "$v" "$(git rev-parse --short HEAD)"
done

git branch -M version-ladder main
echo
echo "main rebuilt: $(git rev-list --count HEAD) commits, $(git tag | grep -c '^v') tags"
echo "HEAD targets Spark $(python3 -c "import json; print(list(json.load(open('tools/versions.json')))[-1])")"
